package com.backend.backend.service.export;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import com.backend.backend.config.AppProperties;
import com.backend.backend.model.Customization;
import com.backend.backend.model.ExportFormat;
import com.backend.backend.service.matching.CustomizationEngine;
import com.backend.backend.service.matching.MatchingEnginesTest;
import com.backend.backend.util.DocumentTextExtractor;
import com.backend.backend.validation.UploadValidator.Kind;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.List;
import org.junit.jupiter.api.Test;

class CvExportServiceTest {

    private static final Path TECTONIC = Path.of("tools", "tectonic", "tectonic.exe");

    private final CustomizationEngine engine = new CustomizationEngine();
    private final LatexCvRenderer latex = new LatexCvRenderer();
    private final DocumentTextExtractor extractor = new DocumentTextExtractor();

    private static LatexCompiler compiler(boolean enabled) {
        return new LatexCompiler(new AppProperties(null, null, null, null,
                new AppProperties.Latex(enabled, TECTONIC.toString(), Duration.ofSeconds(240))));
    }

    private CvDocument document() {
        var cv = MatchingEnginesTest.CV;
        var target = MatchingEnginesTest.FRONTEND;
        var decisions = engine.buildPlan(cv, target);
        return new CvDocumentFactory(engine).build(cv, target, new Customization(engine.buildSections(cv, target, decisions), decisions));
    }

    @Test
    void latexUsesTheResumeTemplateAndEscapesUserText() {
        String tex = latex.render(document());

        assertThat(tex).startsWith("% Generated by CVPilot AI").contains("\\usepackage{titlesec}", "\\begin{document}", "\\end{document}");
        assertThat(tex).contains("{\\LARGE\\bfseries Raed Zayoud}", "\\section*{Professional Experience}",
                "\\cvheading{Software Engineer\\cvsep Novadev}{Tunis\\hspace{1.2em}Mar 2022 – Present}",
                "\\cvtech{Spring Boot, Angular}", "\\section*{Achievements}");
        // "&", "%" and "#" in CV text are escaped, so they cannot break or inject LaTeX.
        assertThat(tex).contains("(50\\% of teams) \\& \\#1 in C\\# track");
        assertThat(LatexCvRenderer.url("https://x.com/a b}{\\evil")).doesNotContain("{", "}", "\\evil", " ");
    }

    @Test
    void handEditedSectionsAreExportedVerbatim() {
        var cv = MatchingEnginesTest.CV;
        var target = MatchingEnginesTest.FRONTEND;
        var decisions = engine.buildPlan(cv, target);
        var sections = engine.buildSections(cv, target, decisions);
        sections.stream().filter(s -> s.getKey().equals("experience")).forEach(s -> s.setProposed("My own experience text."));

        CvDocument doc = new CvDocumentFactory(engine).build(cv, target, new Customization(sections, decisions));

        assertThat(doc.experienceText()).isEqualTo("My own experience text.");
        assertThat(doc.experiences()).isEmpty();
        assertThat(doc.projectsText()).isNull();
        assertThat(doc.projects()).isNotEmpty();
    }

    @Test
    void docxAndFallbackPdfContainTheWholeCv() throws Exception {
        CvExportService service = new CvExportService(latex, compiler(false));
        for (ExportFormat format : List.of(ExportFormat.DOCX, ExportFormat.PDF)) {
            CvExportService.ExportedFile file = service.render(document(), format);
            String text = extractor.extract(format == ExportFormat.PDF ? Kind.PDF : Kind.DOCX, file.content());

            assertThat(text).contains("Raed Zayoud", "Novadev", "MedTech Solutions", "National Engineering School of Tunis",
                    "AWS Certified Cloud Practitioner", "Technologies: Spring Boot, Angular", "4th place");
            Files.write(Path.of("target", "sample-export." + file.extension()), file.content());
        }
    }

    @Test
    void anEmptySkillsListProducesNoTechnicalSkillsSectionInAnyFormat() throws Exception {
        var cv = MatchingEnginesTest.CV;
        var noSkills = new com.backend.backend.model.CvProfile(cv.personalInfo(), cv.professionalTitle(), cv.summary(), List.of(),
                cv.experiences(), cv.education(), cv.projects(), cv.certifications(), cv.languages(), cv.achievements());
        CvDocument doc = new CvDocumentFactory(engine).fromProfile(noSkills, com.backend.backend.model.CvSections.DEFAULT_ORDER);

        String tex = latex.render(doc);
        assertThat(tex).doesNotContain("Technical Skills").contains("\\section*{Summary}", "\\section*{Professional Experience}");

        CvExportService fallback = new CvExportService(latex, compiler(false));
        for (ExportFormat format : List.of(ExportFormat.DOCX, ExportFormat.PDF)) {
            String text = extractor.extract(format == ExportFormat.PDF ? Kind.PDF : Kind.DOCX, fallback.render(doc, format).content());
            assertThat(text).doesNotContain("Technical Skills").contains("Professional Experience", "Novadev");
        }

        if (Files.isExecutable(TECTONIC)) {
            byte[] compiled = new CvExportService(latex, compiler(true)).render(doc, ExportFormat.PDF).content();
            assertThat(extractor.extract(Kind.PDF, compiled)).doesNotContain("Technical Skills").contains("Professional Experience");
        }
    }

    @Test
    void pdfIsCompiledFromTheLatexTemplateWhenTectonicIsInstalled() throws Exception {
        assumeTrue(Files.isExecutable(TECTONIC), "Tectonic not installed in tools/tectonic");
        CvExportService.ExportedFile file = new CvExportService(latex, compiler(true)).render(document(), ExportFormat.PDF);

        String text = extractor.extract(Kind.PDF, file.content());
        assertThat(text).contains("Raed Zayoud", "Professional Experience", "Technologies: Spring Boot, Angular");
        Files.write(Path.of("target", "sample-latex.pdf"), file.content());
        Files.writeString(Path.of("target", "sample-latex.tex"), latex.render(document()), StandardCharsets.UTF_8);
    }
}
